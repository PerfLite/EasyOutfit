    class Localization
    {
    public:
        static const Strings& Get(const std::string& a_lang)
        {
            if (a_lang == "en") {
                return STR_EN;
            }
            // If explicit "ru" or "auto", detect or default to Russian!
            if (a_lang == "ru") {
                return STR_RU;
            }

            static std::string detectedLang = DetectSystemLanguage();
            return (detectedLang == "en") ? STR_EN : STR_RU;
        }

    private:
        static std::string DetectSystemLanguage()
        {
            auto* iniCollection = RE::INISettingCollection::GetSingleton();
            if (iniCollection) {
                auto* langSetting = iniCollection->GetSetting("sLanguage:General");
                if (langSetting && langSetting->data.s) {
                    std::string s = langSetting->data.s;
                    for (char& c : s) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
                    if (s.find("english") != std::string::npos) {
                        return "en";
                    }
                    if (s.find("russian") != std::string::npos || s.find("rus") != std::string::npos) {
                        return "ru";
                    }
                }
            }
            return "ru";
        }
    };
